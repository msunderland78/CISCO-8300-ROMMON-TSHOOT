#!/usr/bin/env python3
"""Reproduce non-generative inspection crops of the received CH341A hardware.

Uses macOS sips to crop/rotate original pixels. No sharpening, resampling,
component reconstruction, hardware access, or network access is performed.
Coordinates apply only to this project's 4032x3024 source photographs.
"""

import argparse
import hashlib
from pathlib import Path
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
# source, output, crop height/width, source y/x offset, clockwise rotation
CROPS = (
    ("IMG_1264.jpeg", "adapter-translator-upright.png", 750, 650, 300, 1250, 270),
    ("IMG_1264.jpeg", "adapter-regulator-readable.png", 550, 650, 550, 2100, 180),
    ("IMG_1268.jpeg", "programmer-labels-readable.png", 1100, 1900, 950, 800, 180),
)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / "Photos")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "Photos/inspection")
    args = parser.parse_args()
    sips = shutil.which("sips")
    if not sips:
        parser.error("This inspection utility requires macOS sips")
    source_dir = args.source_dir.resolve()
    output_dir = args.output_dir.resolve()
    sources = {source_dir / item[0] for item in CROPS}
    before = {p: sha256(p) for p in sources}
    for path in sources:
        dimensions = run(sips, "-g", "pixelWidth", "-g", "pixelHeight", str(path))
        if "pixelWidth: 4032" not in dimensions or "pixelHeight: 3024" not in dimensions:
            parser.error("Unexpected source dimensions: " + path.name)
    output_dir.mkdir(parents=True, exist_ok=True)
    notes = [
        "CH341A PHOTO INSPECTION DERIVATIVES",
        "Generated by scripts/make_programmer_inspection_crops.py.",
        "Original pixels cropped/rotated using macOS sips; no reconstruction,",
        "sharpening, resampling, or AI image generation. Originals are unchanged.",
        "Source offsets and dimensions are pixels; rotation is clockwise.",
        "A crop aids inspection but cannot establish unreadable markings or",
        "electrical behavior. Refer to the source photographs and bench tests.",
        "",
    ]
    with tempfile.TemporaryDirectory(prefix="ch341a-inspection-") as temporary:
        for name, output, height, width, y, x, rotation in CROPS:
            source = source_dir / name
            target = output_dir / output
            if target == source or target in sources:
                parser.error("Output must not overwrite an original photograph")
            intermediate = Path(temporary) / output
            run(sips, "-s", "format", "png", "--cropToHeightWidth", str(height), str(width),
                "--cropOffset", str(y), str(x), str(source), "--out", str(intermediate))
            run(sips, "-r", str(rotation), str(intermediate), "--out", str(target))
            notes.extend([
                "Output: " + output,
                "Source: " + name,
                "Source SHA256: " + before[source],
                f"Crop HxW: {height}x{width}; offset Y,X: {y},{x}; rotation: {rotation}",
                "",
            ])
    if any(sha256(path) != digest for path, digest in before.items()):
        raise RuntimeError("Source photograph changed during inspection generation")
    (output_dir / "README.txt").write_text("\n".join(notes))
    print("Created three inspection crops; source photograph hashes unchanged.")


if __name__ == "__main__":
    main()
